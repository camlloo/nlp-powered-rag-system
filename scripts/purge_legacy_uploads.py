"""Preview and purge legacy local uploads during a manually enforced maintenance window.

Before apply or resume, STOP the API, all workers and all other database/filesystem
writers, keep them stopped throughout the operation, and verify a restorable backup.
This script does not stop processes. Database and file deletion are not atomic.
Never load .env: supply LEGACY_PURGE_DSN explicitly. Preview emits JSON; apply emits
JSON lines including a recovery token before commit; save this sensitive output.
"""

from __future__ import annotations

import argparse
import datetime as dt
import hashlib
import hmac
import json
import ntpath
import os
import re
import stat
import sys
from collections import defaultdict
from pathlib import Path
from typing import Any

# This is exactly the name format generated by app.parsers.intake.save_upload.
UPLOAD_URI = re.compile(r"uploads/[0-9a-f]{32}\.(?:txt|md|docx|pdf)\Z", re.ASCII)

WARNINGS = [
    "执行者必须先停止 API、全部 worker 及其他数据库和文件系统写入方，"
    "核实可恢复备份；维护期间保持停止，本工具不会关闭进程。",
    "仅匹配 uploads/<32位小写十六进制>.<txt|md|docx|pdf>；"
    "版本创建时间早于截止时间，整文档所有版本均须符合条件。",
    "不扫描未登记孤儿文件。保留的 QA 审计可能仍包含原文摘录和历史引用。",
    "数据库与文件删除不是原子操作。逐文件结果、恢复令牌和预览清单应妥善保存。",
    "受影响的活跃快照会失效；其他存活文档需要重建索引，期间检索可能不可用。",
]


def parse_cutoff(value: str) -> dt.datetime:
    """Require an unambiguous instant, not a local time or date."""
    try:
        result = dt.datetime.fromisoformat(value.replace("Z", "+00:00"))
    except ValueError as exc:
        raise argparse.ArgumentTypeError("时间必须是带时区的 ISO 8601 时间") from exc
    if result.tzinfo is None or result.utcoffset() is None:
        raise argparse.ArgumentTypeError("时间必须包含时区，例如 2026-01-01T00:00:00Z")
    return result.astimezone(dt.UTC)


def trusted_upload_uri(uri: str) -> bool:
    return isinstance(uri, str) and UPLOAD_URI.fullmatch(uri) is not None


def _uri_alias_key(uri: str) -> str:
    # Conservative Windows-style case/separator/dot normalization even on Unix.
    # Filesystem symlinks, absolute paths and alternate spellings cannot be fully
    # proven equivalent from URI strings; this report is not a deletion permit.
    return ntpath.normcase(ntpath.normpath(uri.replace("/", "\\")))


def inspect_file(root: Path, uri: str) -> dict[str, Any]:
    """Inspect metadata only, without opening files or following a known link."""
    if not trusted_upload_uri(uri):
        return {"state": "untrusted_uri"}
    target = Path(os.path.abspath(root)) / uri
    parts = [*reversed(target.parents), target]
    for path in parts:
        try:
            info = path.lstat()
        except FileNotFoundError:
            return {"state": "missing", "path": str(target)}
        except OSError as exc:
            return {"state": "error", "path": str(target), "error_type": type(exc).__name__}
        attrs = getattr(info, "st_file_attributes", 0)
        if stat.S_ISLNK(info.st_mode) or attrs & getattr(stat, "FILE_ATTRIBUTE_REPARSE_POINT", 0):
            return {"state": "link_or_reparse", "path": str(target), "component": str(path)}
        if path != target and not stat.S_ISDIR(info.st_mode):
            return {"state": "non_directory_component", "path": str(target)}
    if not stat.S_ISREG(info.st_mode):
        return {"state": "not_regular_file", "path": str(target)}
    return {
        "state": "regular_file",
        "path": str(target),
        "size_bytes": info.st_size,
        "hard_links": info.st_nlink,
    }


def _iso(value: dt.datetime | None) -> str | None:
    return value.isoformat() if value is not None else None


def _manifest_files(value: Any) -> set[int] | None:
    if not isinstance(value, dict) or not isinstance(value.get("files"), list):
        return None
    files = value["files"]
    if any(type(item) is not int or item <= 0 for item in files):
        return None
    return set(files)


def select_versions(
    versions: list[dict[str, Any]], cutoff: dt.datetime
) -> tuple[list[dict[str, Any]], list[dict[str, Any]]]:
    """A document is a candidate only if every version is old and trusted."""
    by_document: dict[int, list[dict[str, Any]]] = defaultdict(list)
    for version in versions:
        by_document[version["document_id"]].append(version)

    selected: list[dict[str, Any]] = []
    skipped: list[dict[str, Any]] = []
    for document_id, doc_versions in sorted(by_document.items()):
        eligible = [
            row for row in doc_versions
            if trusted_upload_uri(row["storage_uri"]) and row["created_at"] < cutoff
        ]
        suspicious_old = [
            row for row in doc_versions
            if isinstance(row["storage_uri"], str)
            and row["storage_uri"].startswith("uploads/")
            and row["created_at"] < cutoff
            and not trusted_upload_uri(row["storage_uri"])
        ]
        if not eligible and not suspicious_old:
            continue
        if len(eligible) != len(doc_versions):
            skipped.append({
                "document_id": document_id,
                "reason": "至少一个版本较新或 URI 不符合本工具的本地命名规则；整文档排除",
                "versions": [
                    {"id": row["version_id"], "storage_uri": row["storage_uri"],
                     "created_at": _iso(row["created_at"])}
                    for row in doc_versions
                ],
            })
            continue
        selected.extend(eligible)
    return selected, skipped


def build_inventory(
    *,
    kb: dict[str, Any],
    versions: list[dict[str, Any]],
    all_uris: list[dict[str, Any]],
    indexes: list[dict[str, Any]],
    chunks: list[dict[str, Any]],
    jobs: list[dict[str, Any]],
    active_refs: list[dict[str, Any]],
    citations: list[dict[str, Any]],
    qa_requests: list[dict[str, Any]],
    root: Path,
    cutoff: dt.datetime,
) -> dict[str, Any]:
    """Pure selection/aggregation except for read-only filesystem metadata."""
    selected, skipped = select_versions(versions, cutoff)
    selected_ids = {row["version_id"] for row in selected}
    uri_refs: dict[str, list[dict[str, Any]]] = defaultdict(list)
    for row in all_uris:
        if isinstance(row["storage_uri"], str):
            uri_refs[_uri_alias_key(row["storage_uri"])].append(row)

    documents: dict[int, dict[str, Any]] = {}
    for row in selected:
        doc = documents.setdefault(row["document_id"], {
            "id": row["document_id"],
            "title": row["document_title"],
            "deleted_at": _iso(row["deleted_at"]),
            "versions": [],
        })
        aliases = [
            {"version_id": other["version_id"], "kb_id": other["kb_id"],
             "document_id": other["document_id"], "storage_uri": other["storage_uri"]}
            for other in uri_refs[_uri_alias_key(row["storage_uri"])]
            if other["version_id"] != row["version_id"]
        ]
        doc["versions"].append({
            "id": row["version_id"],
            "version_no": row["version_no"],
            "storage_uri": row["storage_uri"],
            "created_at": _iso(row["created_at"]),
            "parse_status": row["parse_status"],
            "file": inspect_file(root, row["storage_uri"]),
            "possible_uri_aliases": aliases,
        })

    chunks_by_index: dict[int, list[dict[str, Any]]] = defaultdict(list)
    for chunk in chunks:
        chunks_by_index[chunk["index_id"]].append(chunk)
    active_by_index: dict[int, list[int]] = defaultdict(list)
    for ref in active_refs:
        active_by_index[ref["active_index_id"]].append(ref["id"])

    index_reports = []
    for index in indexes:
        index_chunks = chunks_by_index[index["id"]]
        target_chunks = [c for c in index_chunks if c["doc_version_id"] in selected_ids]
        manifest = _manifest_files(index["manifest_json"])
        manifest_matches = sorted((manifest or set()) & selected_ids)
        # An unknown manifest in the KB is significant even if there are no chunks.
        if not target_chunks and not manifest_matches and not (selected_ids and manifest is None):
            continue
        index_reports.append({
            "id": index["id"], "kb_id": index["kb_id"], "status": index["status"],
            "source_revision": index["source_revision"],
            "active_for_kb_ids": active_by_index[index["id"]],
            "manifest_valid": manifest is not None,
            "target_manifest_version_ids": manifest_matches,
            "target_chunks": [
                {"id": c["id"], "document_id": c["document_id"],
                 "doc_version_id": c["doc_version_id"], "has_embedding": c["has_embedding"]}
                for c in target_chunks
            ],
            "other_chunk_count": len(index_chunks) - len(target_chunks),
            "other_chunks": [
                {"id": c["id"], "document_id": c["document_id"],
                 "doc_version_id": c["doc_version_id"], "has_embedding": c["has_embedding"]}
                for c in index_chunks if c["doc_version_id"] not in selected_ids
            ],
            "other_manifest_version_count": len((manifest or set()) - selected_ids),
            "other_manifest_version_ids": sorted((manifest or set()) - selected_ids),
        })

    relevant_jobs = [
        job for job in jobs
        if job["doc_version_id"] in selected_ids
        or (job["kb_id"] == kb["id"] and job["status"] in ("queued", "running"))
    ]
    target_chunk_ids = {c["id"] for c in chunks if c["doc_version_id"] in selected_ids}
    relevant_citations = [
        {"id": item["id"], "qa_request_id": item["qa_request_id"],
         "doc_version_id": item["doc_version_id"], "chunk_id": item["chunk_id"]}
        for item in citations
        if item["doc_version_id"] in selected_ids or item["chunk_id"] in target_chunk_ids
    ]
    return {
        "mode": "preview",
        "cutoff_exclusive_utc": cutoff.isoformat(),
        "storage_root": str(Path(os.path.abspath(root))),
        "kb": kb,
        "documents": list(documents.values()),
        "skipped_documents": skipped,
        "indexes_referencing_targets_or_unknown": index_reports,
        "relevant_jobs": relevant_jobs,
        "retained_qa_citations": relevant_citations,
        "retained_qa_requests_for_reported_indexes": qa_requests,
        "warnings": WARNINGS + [
            "URI 别名检查只是提示，不覆盖所有绝对路径、符号链接和文件系统别名。",
            "数据库快照和文件元数据不具备跨系统原子性；该清单可能立即过期。",
            "输出可能包含文档标题和路径等敏感信息，应妥善保管。",
        ],
    }


def _rows(cursor: Any, sql: str, params: tuple[Any, ...] = ()) -> list[dict[str, Any]]:
    cursor.execute(sql, params)
    return list(cursor.fetchall())


def collect_inventory(
    connection: Any, kb_id: int, root: Path, cutoff: dt.datetime, *, read_only: bool = True
) -> dict[str, Any]:
    """Collect the preview in a read-only snapshot, or inside a caller's locked transaction."""
    with connection.cursor() as cursor:
        if read_only:
            cursor.execute("SET TRANSACTION ISOLATION LEVEL REPEATABLE READ, READ ONLY")
            _session_safety(cursor)
        kb_rows = _rows(cursor, """
            SELECT id, tenant_id, name, active_index_id, data_revision, acl_revision, deleted_at
            FROM kb_collection WHERE id = %s
        """, (kb_id,))
        if not kb_rows:
            raise ValueError("指定的知识库不存在")
        if "deleted_at" in kb_rows[0]:
            kb_rows[0]["deleted_at"] = _iso(kb_rows[0]["deleted_at"])
        versions = _rows(cursor, """
            SELECT d.id AS document_id, d.title AS document_title, d.deleted_at,
                   v.id AS version_id, v.version_no, v.storage_uri, v.created_at, v.parse_status
            FROM kb_document d JOIN kb_document_version v
              ON v.kb_id = d.kb_id AND v.document_id = d.id
            WHERE d.kb_id = %s ORDER BY d.id, v.id
        """, (kb_id,))
        selected, _ = select_versions(versions, cutoff)
        candidate_ids = [v["version_id"] for v in selected]
        candidate_id_set = set(candidate_ids)
        # Global URI and manifest metadata is necessary to flag cross-KB references.
        all_uris = _rows(cursor, """
            SELECT id AS version_id, kb_id, document_id, storage_uri
            FROM kb_document_version ORDER BY id
        """)
        all_indexes = _rows(cursor, """
            SELECT id, kb_id, status, source_revision, manifest_json FROM kb_index ORDER BY id
        """)
        target_chunks = _rows(cursor, """
            SELECT id, index_id FROM kb_chunk WHERE doc_version_id = ANY(%s) ORDER BY id
        """, (candidate_ids,))
        target_index_ids = {row["index_id"] for row in target_chunks}
        indexes = []
        for index in all_indexes:
            manifest = _manifest_files(index["manifest_json"])
            if (index["id"] in target_index_ids or (manifest or set()) & candidate_id_set
                    or (candidate_ids and manifest is None)):
                indexes.append(index)
        index_ids = [row["id"] for row in indexes]
        chunks = _rows(cursor, """
            SELECT c.id, c.index_id, c.document_id, c.doc_version_id,
                   EXISTS (SELECT 1 FROM kb_embedding e WHERE e.chunk_id = c.id) AS has_embedding
            FROM kb_chunk c WHERE c.index_id = ANY(%s) ORDER BY c.id
        """, (index_ids,))
        jobs = _rows(cursor, """
            SELECT id, kb_id, doc_version_id, job_type, status, stage
            FROM ingest_job WHERE kb_id = %s OR doc_version_id = ANY(%s) ORDER BY id
        """, (kb_id, candidate_ids))
        active_refs = _rows(cursor, """
            SELECT id, active_index_id FROM kb_collection WHERE active_index_id = ANY(%s)
        """, (index_ids,))
        target_chunk_ids = [c["id"] for c in target_chunks]
        citations = _rows(cursor, """
            SELECT id, qa_request_id, doc_version_id, chunk_id FROM qa_citation
            WHERE doc_version_id = ANY(%s) OR chunk_id = ANY(%s) ORDER BY id
        """, (candidate_ids, target_chunk_ids))
        qa_requests = _rows(cursor, """
            SELECT id, kb_id, index_id FROM qa_request WHERE index_id = ANY(%s) ORDER BY id
        """, (index_ids,))
    result = build_inventory(
        kb=kb_rows[0], versions=versions, all_uris=all_uris, indexes=indexes,
        chunks=chunks, jobs=jobs, active_refs=active_refs, citations=citations,
        qa_requests=qa_requests, root=root, cutoff=cutoff,
    )
    active_id = kb_rows[0]["active_index_id"]
    result["active_index"] = next(
        ({"id": row["id"], "kb_id": row["kb_id"], "status": row["status"]}
         for row in all_indexes if row["id"] == active_id), None,
    )
    return result


def preview_digest(inventory: dict[str, Any]) -> str:
    payload = {key: value for key, value in inventory.items() if key != "preview_sha256"}
    encoded = json.dumps(payload, sort_keys=True, ensure_ascii=False, separators=(",", ":"))
    return hashlib.sha256(encoded.encode("utf-8")).hexdigest()


class UnsafePurge(Exception):
    """The operation could not be proven safe; no database changes should commit."""


def _emit(event: dict[str, Any]) -> None:
    print(json.dumps(event, ensure_ascii=False), flush=True)


def _secret_hash(secret: str | None) -> str:
    if not secret or not re.fullmatch(r"[0-9a-f]{64}", secret):
        raise UnsafePurge("LEGACY_PURGE_RECOVERY_SECRET 必须是事先保存的 64 位小写十六进制随机值")
    return hashlib.sha256(b"legacy-purge-v1:" + bytes.fromhex(secret)).hexdigest()


def _manifest_digest(files: dict[str, bytes]) -> str:
    value = [[uri, digest.hex()] for uri, digest in sorted(files.items())]
    return hashlib.sha256(json.dumps(value, separators=(",", ":")).encode()).hexdigest()


def _record_mac(secret: str, run_hash: str, row: dict[str, Any]) -> str:
    fields = [run_hash, row["kb_id"], row["storage_root"], row["uri"],
              bytes(row["file_sha256"]).hex(), row["reindex_job_id"], row["run_size"],
              row["manifest_sha256"], row["state"]]
    encoded = json.dumps(fields, ensure_ascii=False, separators=(",", ":")).encode("utf-8")
    return hmac.new(bytes.fromhex(secret), encoded, hashlib.sha256).hexdigest()


def _verify_journal(rows: list[dict[str, Any]], run_hash: str, secret: str) -> None:
    if not rows:
        raise UnsafePurge("恢复记录不存在；数据库提交可能未发生")
    files = {row["uri"]: bytes(row["file_sha256"]) for row in rows}
    if len(files) != len(rows):
        raise UnsafePurge("恢复记录包含重复路径")
    digest = _manifest_digest(files)
    for row in rows:
        if (not trusted_upload_uri(row["uri"]) or len(bytes(row["file_sha256"])) != 32
                or row["run_size"] != len(rows) or row["manifest_sha256"] != digest
                or row["state"] not in {"pending", "deleted", "missing", "shared"}
                or not hmac.compare_digest(row["record_mac"], _record_mac(secret, run_hash, row))):
            raise UnsafePurge("恢复记录完整性校验失败，拒绝文件操作")
    if len({row["reindex_job_id"] for row in rows}) != 1:
        raise UnsafePurge("恢复记录的重建任务不一致")


def _journal_table(cursor: Any) -> None:
    # Persistent journal is committed in the same transaction as metadata deletion.
    # A recovery token known before commit resolves even an indeterminate COMMIT.
    cursor.execute("""
        CREATE TABLE IF NOT EXISTS public.legacy_upload_purge_journal_v1 (
            run_hash text NOT NULL,
            kb_id bigint NOT NULL,
            storage_root text NOT NULL,
            uri text NOT NULL,
            file_sha256 bytea NOT NULL,
            reindex_job_id bigint,
            run_size integer NOT NULL,
            manifest_sha256 text NOT NULL,
            state text NOT NULL CHECK (state IN ('pending','deleted','missing','shared')),
            record_mac text NOT NULL,
            PRIMARY KEY (run_hash, uri)
        )
    """)


def _session_safety(cursor: Any) -> None:
    # RLS must not hide another version referencing the same physical file.
    cursor.execute("SET LOCAL row_security = off")
    cursor.execute("SET LOCAL search_path = pg_catalog, public, pg_temp")


def _locks(cursor: Any) -> None:
    # No phantoms from non-cooperating SQL writers during selection/commit. The
    # operator still must stop all processes, including writers outside PostgreSQL.
    cursor.execute("SET LOCAL lock_timeout = '5s'")
    cursor.execute("""
        LOCK TABLE kb_collection, kb_document, kb_document_version, kb_index,
                   kb_chunk, kb_embedding, ingest_job IN EXCLUSIVE MODE
    """)


def _safe_manifest(manifest: Any, selected: set[int]) -> dict[str, Any]:
    files = _manifest_files(manifest)
    if files is None or set(manifest) - {"files", "chunk_counts", "totals"}:
        raise UnsafePurge("快照清单格式未知，无法安全移除版本引用")
    counts = manifest.get("chunk_counts", {})
    if not isinstance(counts, dict) or any(
        not isinstance(key, str) or not key.isascii() or not key.isdigit()
        or type(value) is not int or value < 0 for key, value in counts.items()
    ):
        raise UnsafePurge("快照块计数格式未知")
    totals = manifest.get("totals", {})
    allowed_totals = {
        "chunks", "embedding_prompt_tokens", "embedding_total_tokens", "vector_cache_hits"
    }
    if not isinstance(totals, dict) or any(
        key not in allowed_totals or type(value) is not int or value < 0
        for key, value in totals.items()
    ):
        raise UnsafePurge("快照汇总格式未知")
    # Totals no longer describe the modified snapshot: discard the aggregates.
    result: dict[str, Any] = {"files": [v for v in manifest["files"] if v not in selected]}
    if "chunk_counts" in manifest:
        result["chunk_counts"] = {k: v for k, v in counts.items() if int(k) not in selected}
    return result


def _preflight(inventory: dict[str, Any]) -> None:
    kb_id = inventory["kb"]["id"]
    if inventory["kb"].get("deleted_at") is not None:
        raise UnsafePurge("知识库已软删除，不适用此工具")
    active_id = inventory["kb"]["active_index_id"]
    active = inventory.get("active_index")
    if active_id is not None and (not active or active["id"] != active_id
                                  or active["kb_id"] != kb_id or active["status"] != "ready"):
        raise UnsafePurge("当前活跃索引不存在、归属不符或状态不是 ready")
    for job in inventory["relevant_jobs"]:
        if job["status"] in {"queued", "running"}:
            raise UnsafePurge(f"存在未完成工作任务 id={job['id']}，拒绝执行")
    for index in inventory["indexes_referencing_targets_or_unknown"]:
        if not index["manifest_valid"] or index["status"] == "building":
            raise UnsafePurge(f"索引 id={index['id']} 的清单未知或仍在构建")
        if index["kb_id"] != kb_id or any(ref != kb_id for ref in index["active_for_kb_ids"]):
            raise UnsafePurge(f"索引 id={index['id']} 存在跨知识库引用")


def apply_database(
    connection: Any, kb_id: int, root: Path, cutoff: dt.datetime,
    expected_digest: str, run_hash: str, secret: str,
) -> dict[str, Any]:
    """Prepare, journal, and delete metadata in a single locked transaction."""
    root_text = str(Path(os.path.abspath(root)))
    with connection.cursor() as cursor:
        cursor.execute("SET TRANSACTION ISOLATION LEVEL READ COMMITTED")
        _session_safety(cursor)
        _locks(cursor)
        cursor.execute("SELECT id FROM kb_collection WHERE id = %s FOR UPDATE", (kb_id,))
        if not cursor.fetchone():
            raise UnsafePurge("指定知识库不存在")
    inventory = collect_inventory(connection, kb_id, root, cutoff, read_only=False)
    if not hmac.compare_digest(preview_digest(inventory), expected_digest):
        raise UnsafePurge("预览已变化，请重新预览并核对摘要")
    _preflight(inventory)
    docs = [item["id"] for item in inventory["documents"]]
    versions = [v["id"] for doc in inventory["documents"] for v in doc["versions"]]
    if not versions:
        return {"status": "no_candidates", "kb_id": kb_id}
    affected_indexes = [item["id"] for item in inventory["indexes_referencing_targets_or_unknown"]]
    with connection.cursor() as cursor:
        cursor.execute(
            "SELECT id FROM kb_document WHERE kb_id = %s AND id = ANY(%s) ORDER BY id FOR UPDATE",
            (kb_id, docs),
        )
        if len(cursor.fetchall()) != len(docs):
            raise UnsafePurge("目标文档已变化")
        rows = _rows(cursor, """
            SELECT id, storage_uri, file_sha256 FROM kb_document_version
            WHERE kb_id = %s AND id = ANY(%s) ORDER BY id FOR UPDATE
        """, (kb_id, versions))
        if len(rows) != len(versions):
            raise UnsafePurge("目标版本已变化")
        files: dict[str, bytes] = {}
        for row in rows:
            uri = row["storage_uri"]
            digest = bytes(row["file_sha256"])
            if not trusted_upload_uri(uri) or len(digest) != 32:
                raise UnsafePurge("目标 URI 或文件摘要不可信")
            if uri in files and files[uri] != digest:
                raise UnsafePurge("同一路径对应不同文件摘要")
            files[uri] = digest
        for uri, digest in files.items():
            delete_windows_file(root, uri, digest, delete=False)
        # The current builder only loads MinIO. A surviving succeeded legacy URI
        # would make an automatically queued rebuild fail; preserve everything.
        survivors = _rows(cursor, """
            SELECT v.storage_uri FROM kb_document d
            JOIN kb_document_version v ON v.document_id = d.id AND v.kb_id = d.kb_id
            WHERE d.kb_id = %s AND d.deleted_at IS NULL AND d.id != ALL(%s)
              AND v.parse_status = 'succeeded'
        """, (kb_id, docs))
        if any(not row["storage_uri"].startswith("s3://") for row in survivors):
            raise UnsafePurge("剩余存活文档仍含本地版本，当前重建器只支持 MinIO；拒绝清理")
        cursor.execute("""
            SELECT count(*) AS n FROM kb_document
            WHERE kb_id = %s AND deleted_at IS NULL AND id != ALL(%s)
        """, (kb_id, docs))
        remaining = cursor.fetchone()["n"]
        indexes = _rows(cursor, """
            SELECT id, manifest_json FROM kb_index WHERE kb_id = %s AND id = ANY(%s)
        """, (kb_id, affected_indexes))
        if len(indexes) != len(affected_indexes):
            raise UnsafePurge("索引归属异常")
        cleaned_manifests = {
            index["id"]: _safe_manifest(index["manifest_json"], set(versions))
            for index in indexes
        }
        _journal_table(cursor)
        cursor.execute(
            "SELECT 1 FROM public.legacy_upload_purge_journal_v1 WHERE run_hash = %s LIMIT 1",
            (run_hash,),
        )
        if cursor.fetchone():
            raise UnsafePurge("恢复口令已使用；请使用 --resume 或新口令")
        for index_id, manifest in cleaned_manifests.items():
            cursor.execute("""
                UPDATE kb_index SET status = 'superseded', manifest_json = %s::jsonb
                WHERE kb_id = %s AND id = %s
            """, (json.dumps(manifest), kb_id, index_id))
        cursor.execute("""
            UPDATE kb_collection SET data_revision = data_revision + 1,
                active_index_id = CASE WHEN active_index_id = ANY(%s)
                                       THEN NULL ELSE active_index_id END
            WHERE id = %s
        """, (affected_indexes, kb_id))
        cursor.execute("""
            DELETE FROM kb_embedding WHERE chunk_id IN
              (SELECT id FROM kb_chunk WHERE kb_id = %s AND doc_version_id = ANY(%s))
        """, (kb_id, versions))
        embedding_count = cursor.rowcount
        cursor.execute("DELETE FROM kb_chunk WHERE kb_id = %s AND doc_version_id = ANY(%s)",
                       (kb_id, versions))
        chunk_count = cursor.rowcount
        cursor.execute("""
            UPDATE ingest_job SET doc_version_id = NULL WHERE doc_version_id = ANY(%s)
        """, (versions,))
        job_count = cursor.rowcount
        cursor.execute("DELETE FROM kb_document_version WHERE kb_id = %s AND id = ANY(%s)",
                       (kb_id, versions))
        if cursor.rowcount != len(versions):
            raise UnsafePurge("版本删除数量异常")
        cursor.execute("DELETE FROM kb_document WHERE kb_id = %s AND id = ANY(%s)", (kb_id, docs))
        if cursor.rowcount != len(docs):
            raise UnsafePurge("文档删除数量异常")
        reindex_id = None
        active_id = inventory["kb"]["active_index_id"]
        if remaining and (active_id is None or active_id in affected_indexes):
            cursor.execute("""
                INSERT INTO ingest_job (kb_id, job_type, status, payload_json)
                VALUES (%s, 'reindex', 'queued', '{"reason":"legacy_upload_purge"}'::jsonb)
                RETURNING id
            """, (kb_id,))
            reindex_id = cursor.fetchone()["id"]
        manifest_digest = _manifest_digest(files)
        for uri, digest in sorted(files.items()):
            row = {"kb_id": kb_id, "storage_root": root_text, "uri": uri,
                   "file_sha256": digest, "reindex_job_id": reindex_id, "run_size": len(files),
                   "manifest_sha256": manifest_digest, "state": "pending"}
            cursor.execute("""
                INSERT INTO public.legacy_upload_purge_journal_v1
                  (run_hash, kb_id, storage_root, uri, file_sha256, reindex_job_id,
                   run_size, manifest_sha256, state, record_mac)
                VALUES (%s, %s, %s, %s, %s, %s, %s, %s, %s, %s)
            """, (run_hash, kb_id, root_text, uri, digest, reindex_id, len(files),
                  manifest_digest, "pending", _record_mac(secret, run_hash, row)))
    return {
        "status": "prepared", "kb_id": kb_id, "document_ids": docs,
        "version_ids": versions, "invalidated_index_ids": affected_indexes,
        "embeddings_deleted": embedding_count, "chunks_deleted": chunk_count,
        "job_references_cleared": job_count, "reindex_job_id": reindex_id,
        "file_uris": sorted(files),
    }


def _referenced(uri: str, references: list[str]) -> str | None:
    target = _uri_alias_key(uri)
    for other in references:
        if not isinstance(other, str):
            return "unknown_reference"
        if other.startswith("s3://"):
            continue
        if not trusted_upload_uri(other):
            # An unrecognized local spelling might be a junction, symlink, hardlink,
            # short name, or absolute alias. Do not infer that it is unrelated.
            return "unknown_reference"
        if _uri_alias_key(other) == target:
            return "shared"
    return None


def delete_windows_file(root: Path, uri: str, expected: bytes, *, delete: bool = True) -> str:
    """Verify or delete by a Windows handle; unsupported systems fail closed.

    Directory handles do not share DELETE and are kept open through the operation.
    Maintenance must also exclude external writers; this is not a process manager.
    """
    if os.name != "nt":
        raise UnsafePurge("安全的本地句柄删除目前仅支持 Windows；数据库不应提前提交")
    import ctypes
    from ctypes import wintypes

    if not trusted_upload_uri(uri) or len(expected) != 32:
        raise UnsafePurge("文件 URI 或摘要无效")
    path = Path(os.path.abspath(root)) / uri
    drive, _ = ntpath.splitdrive(str(path))
    if not re.fullmatch(r"[A-Za-z]:", drive):
        raise UnsafePurge("只允许本地盘符路径，不支持 UNC 或设备路径")
    kernel = ctypes.WinDLL("kernel32", use_last_error=True)
    kernel.GetDriveTypeW.argtypes = [wintypes.LPCWSTR]
    kernel.GetDriveTypeW.restype = wintypes.UINT
    if kernel.GetDriveTypeW(drive + "\\") != 3:  # DRIVE_FIXED
        raise UnsafePurge("仅支持本地固定磁盘")
    kernel.CreateFileW.argtypes = [wintypes.LPCWSTR, wintypes.DWORD, wintypes.DWORD,
                                   wintypes.LPVOID, wintypes.DWORD, wintypes.DWORD,
                                   wintypes.HANDLE]
    kernel.CreateFileW.restype = wintypes.HANDLE
    kernel.CloseHandle.argtypes = [wintypes.HANDLE]
    kernel.CloseHandle.restype = wintypes.BOOL
    kernel.GetFileInformationByHandle.argtypes = [wintypes.HANDLE, wintypes.LPVOID]
    kernel.GetFileInformationByHandle.restype = wintypes.BOOL
    kernel.ReadFile.argtypes = [wintypes.HANDLE, wintypes.LPVOID, wintypes.DWORD,
                               ctypes.POINTER(wintypes.DWORD), wintypes.LPVOID]
    kernel.ReadFile.restype = wintypes.BOOL
    kernel.SetFileInformationByHandle.argtypes = [wintypes.HANDLE, ctypes.c_int,
                                                  wintypes.LPVOID, wintypes.DWORD]
    kernel.SetFileInformationByHandle.restype = wintypes.BOOL

    class Information(ctypes.Structure):
        _fields_ = [("attributes", wintypes.DWORD), ("creation", wintypes.FILETIME),
                    ("access", wintypes.FILETIME), ("write", wintypes.FILETIME),
                    ("volume", wintypes.DWORD), ("size_high", wintypes.DWORD),
                    ("size_low", wintypes.DWORD), ("links", wintypes.DWORD),
                    ("index_high", wintypes.DWORD), ("index_low", wintypes.DWORD)]

    class Disposition(ctypes.Structure):
        _fields_ = [("delete", wintypes.BOOLEAN)]

    handles = []
    try:
        for item in [*reversed(path.parents), path]:
            is_target = item == path
            handle = kernel.CreateFileW(
                str(item), 0x00010081 if is_target else 0x80,
                1 if is_target else 3, None, 3,
                0x00200000 | (0 if is_target else 0x02000000), None,
            )
            if handle == ctypes.c_void_p(-1).value:
                code = ctypes.get_last_error()
                if is_target and code in (2, 3):
                    return "missing"
                raise OSError(code, "打开本地文件或目录失败")
            handles.append(handle)
            info = Information()
            if not kernel.GetFileInformationByHandle(handle, ctypes.byref(info)):
                raise OSError(ctypes.get_last_error(), "读取文件属性失败")
            if info.attributes & 0x400:  # FILE_ATTRIBUTE_REPARSE_POINT
                raise UnsafePurge("路径中存在符号链接或重新解析点")
            is_directory = bool(info.attributes & 0x10)
            if is_directory == is_target:
                raise UnsafePurge("路径类型不符合预期")
            if is_target and info.links != 1:
                raise UnsafePurge("文件存在硬链接，无法确认其他引用")
        sha = hashlib.sha256()
        buf = ctypes.create_string_buffer(1024 * 1024)
        while True:
            count = wintypes.DWORD()
            if not kernel.ReadFile(handles[-1], buf, len(buf), ctypes.byref(count), None):
                raise OSError(ctypes.get_last_error(), "读取文件内容失败")
            if not count.value:
                break
            sha.update(buf.raw[:count.value])
        if not hmac.compare_digest(sha.digest(), expected):
            raise UnsafePurge("文件摘要与已登记版本不符")
        if not delete:
            return "verified"
        disposition = Disposition(True)
        if not kernel.SetFileInformationByHandle(handles[-1], 4, ctypes.byref(disposition),
                                                  ctypes.sizeof(disposition)):
            raise OSError(ctypes.get_last_error(), "删除文件失败")
        return "deleted"
    finally:
        close_failed = False
        for handle in reversed(handles):
            if not kernel.CloseHandle(handle):
                close_failed = True
        if close_failed:
            raise OSError("关闭文件句柄失败，删除结果不确定")


def resume_files(
    connection: Any, run_hash: str, secret: str, kb_id: int, root: Path
) -> dict[str, Any]:
    """Check all references and process journal entries; commit each file outcome."""
    root_text = str(Path(os.path.abspath(root)))
    with connection.cursor() as cursor:
        _session_safety(cursor)
        cursor.execute("SELECT to_regclass('public.legacy_upload_purge_journal_v1') AS name")
        if cursor.fetchone()["name"] is None:
            raise UnsafePurge("未发现恢复记录；数据库提交可能未发生")
        rows = _rows(cursor, """
            SELECT kb_id, storage_root, uri, file_sha256, state, reindex_job_id,
                   run_size, manifest_sha256, record_mac
            FROM public.legacy_upload_purge_journal_v1 WHERE run_hash = %s ORDER BY uri
        """, (run_hash,))
        _verify_journal(rows, run_hash, secret)
        if any(r["kb_id"] != kb_id or r["storage_root"] != root_text for r in rows):
            raise UnsafePurge("恢复记录的 KB/存储根目录不匹配")
    connection.rollback()  # Release initial read-only snapshot before locking each file.
    outcomes = []
    for row in rows:
        uri = row["uri"]
        if row["state"] in {"deleted", "missing"}:
            outcome = {"uri": uri, "state": row["state"], "previously_recorded": True}
            outcomes.append(outcome)
            _emit({"event": "file_result", **outcome})
            continue
        try:
            with connection.cursor() as cursor:
                cursor.execute("SET TRANSACTION ISOLATION LEVEL READ COMMITTED")
                _session_safety(cursor)
                cursor.execute("SET LOCAL lock_timeout = '5s'")
                cursor.execute("LOCK TABLE kb_document_version, ingest_job IN SHARE MODE")
                cursor.execute("""
                    SELECT kb_id, storage_root, uri, file_sha256, state, reindex_job_id,
                           run_size, manifest_sha256, record_mac
                    FROM public.legacy_upload_purge_journal_v1
                    WHERE run_hash = %s AND uri = %s FOR UPDATE
                """, (run_hash, uri))
                locked = cursor.fetchone()
                if locked is None or locked != row:
                    raise UnsafePurge("恢复记录已变化，请重新运行 --resume")
                jobs = _rows(cursor, """
                    SELECT id, status FROM ingest_job
                    WHERE kb_id = %s AND status IN ('queued', 'running') ORDER BY id
                """, (kb_id,))
                if any(j["id"] != row["reindex_job_id"] or j["status"] != "queued" for j in jobs):
                    raise UnsafePurge("存在非本次清理排队重建的未完成工作任务")
                references = [r["storage_uri"] for r in _rows(
                    cursor, "SELECT storage_uri FROM kb_document_version ORDER BY id"
                )]
                reference = _referenced(uri, references)
                if reference == "shared":
                    state = "shared"
                elif reference:
                    raise UnsafePurge("存在无法排除的非规范本地路径引用")
                else:
                    state = delete_windows_file(root, uri, bytes(row["file_sha256"]))
                updated = {**row, "state": state}
                mac = _record_mac(secret, run_hash, updated)
                cursor.execute("""
                    UPDATE public.legacy_upload_purge_journal_v1 SET state = %s, record_mac = %s
                    WHERE run_hash = %s AND uri = %s AND kb_id = %s AND storage_root = %s
                """, (state, mac, run_hash, uri, kb_id, root_text))
                if cursor.rowcount != 1:
                    raise UnsafePurge("恢复记录已变化")
            connection.commit()
            outcome = {"uri": uri, "state": state}
        except Exception as exc:  # noqa: BLE001 -- report every failure, never claim completion
            rollback_error = None
            try:
                connection.rollback()
            except Exception as rollback_exc:  # noqa: BLE001
                rollback_error = type(rollback_exc).__name__
            detail = str(exc) if isinstance(exc, UnsafePurge) else type(exc).__name__
            outcome = {"uri": uri, "state": "failed_or_unrecorded", "error": detail}
            if rollback_error:
                outcome["rollback_error"] = rollback_error
        outcomes.append(outcome)
        _emit({"event": "file_result", **outcome})
    return {"status": "complete" if all(o["state"] in {"deleted", "missing"} for o in outcomes)
            else "incomplete", "files": outcomes, "reindex_job_id": rows[0]["reindex_job_id"]}


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--kb-id", type=int, required=True, help="唯一目标知识库 ID")
    parser.add_argument("--created-before", type=parse_cutoff, help="预览截止时间（不含，需时区）")
    parser.add_argument("--storage-dir", type=Path, required=True, help="旧本地存储根目录")
    modes = parser.add_mutually_exclusive_group()
    modes.add_argument("--apply", action="store_true", help="维护期执行数据库和文件清理")
    modes.add_argument("--resume", action="store_true", help="恢复同一清理任务的文件阶段")
    parser.add_argument("--maintenance-confirmed", action="store_true", help="确认停服及核实备份")
    parser.add_argument("--preview-sha256", help="先前只读预览的 SHA-256 摘要")
    args = parser.parse_args(argv)
    if args.kb_id < 1:
        parser.error("--kb-id 必须为正整数")
    if not args.resume and args.created_before is None:
        parser.error("预览和执行需要 --created-before")
    if args.apply or args.resume:
        if not args.maintenance_confirmed:
            print("必须先停 API、所有 worker 和写入方、核实备份并指定 --maintenance-confirmed。",
                  file=sys.stderr)
            return 2
        if os.name != "nt":
            print("执行仅支持 Windows 本地固定磁盘；未连接数据库。", file=sys.stderr)
            return 2
        drive, _ = ntpath.splitdrive(os.path.abspath(args.storage_dir))
        if not re.fullmatch(r"[A-Za-z]:", drive):
            print("执行仅支持本地盘符路径；未连接数据库。", file=sys.stderr)
            return 2
        try:
            secret = os.environ.get("LEGACY_PURGE_RECOVERY_SECRET")
            run_hash = _secret_hash(secret)
        except UnsafePurge as exc:
            print(str(exc), file=sys.stderr)
            return 2
        if args.apply and not re.fullmatch(r"[0-9a-f]{64}", args.preview_sha256 or ""):
            print("--apply 必须提供先前预览输出的 --preview-sha256。", file=sys.stderr)
            return 2
    dsn = os.environ.get("LEGACY_PURGE_DSN")
    if not dsn:
        print("请通过 LEGACY_PURGE_DSN 显式提供 PostgreSQL 连接。", file=sys.stderr)
        return 2
    connection = None
    commit_attempted = False
    committed = False
    try:
        import psycopg
        from psycopg.rows import dict_row

        connection = psycopg.connect(dsn, row_factory=dict_row, connect_timeout=10)
        if args.resume:
            result = resume_files(connection, run_hash, secret, args.kb_id, args.storage_dir)
            _emit({"event": "summary", **result})
            return 0 if result["status"] == "complete" else 1
        if args.apply:
            result = apply_database(connection, args.kb_id, args.storage_dir,
                                    args.created_before, args.preview_sha256, run_hash, secret)
            _emit({"event": "database_prepared", **result, "recovery_id": run_hash})
            if result["status"] == "no_candidates":
                connection.rollback()
                return 0
            commit_attempted = True
            connection.commit()
            committed = True
            _emit({"event": "database_committed", "recovery_id": run_hash})
            files = resume_files(connection, run_hash, secret, args.kb_id, args.storage_dir)
            _emit({"event": "summary", **files})
            return 0 if files["status"] == "complete" else 1
        result = collect_inventory(connection, args.kb_id, args.storage_dir, args.created_before)
        result["preview_sha256"] = preview_digest(result)
        connection.rollback()
        print(json.dumps(result, ensure_ascii=False, indent=2))
        return 0
    except Exception as exc:  # noqa: BLE001 -- avoid leaking driver DSNs or file contents
        rollback_error = None
        if connection is not None:
            try:
                connection.rollback()
            except Exception as rollback_exc:  # noqa: BLE001
                rollback_error = type(rollback_exc).__name__
        message = str(exc) if isinstance(exc, UnsafePurge) else type(exc).__name__
        if rollback_error:
            message += f"；回滚失败：{rollback_error}"
        if committed or commit_attempted:
            print(
                f"执行失败：{message}；提交结果可能不确定。"
                "保持维护期并使用同一恢复口令 --resume。", file=sys.stderr,
            )
        else:
            print(f"执行失败：{message}；没有执行文件删除。", file=sys.stderr)
        return 1
    finally:
        if connection is not None:
            connection.close()


if __name__ == "__main__":
    raise SystemExit(main())
